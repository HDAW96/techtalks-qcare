package com.example.entity;

import jakarta.persistence.*;
import java.time.LocalDateTime;

/**
 * One person's place in a doctor's queue for a day. Walk-ins have no appointment,
 * so appointment_id is nullable.
 */
@Entity
@Table(
        name = "queue_ticket",
        uniqueConstraints = {
                @UniqueConstraint(
                        name = "uk_queue_ticket_number",
                        columnNames = {"queue_id", "ticket_number"}
                )
        }
)
public class QueueTicket {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "ticket_id")
    private Integer ticketId;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "queue_id", nullable = false)
    private Queue queue;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "patient_id", nullable = false)
    private Patient patient;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "service_id", nullable = false)
    private MedicalService medicalService;

    /** Null for a walk-in who arrived without booking. */
    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "appointment_id", nullable = true)
    private Appointment appointment;

    @Column(name = "ticket_number", nullable = false)
    private Integer ticketNumber;

    /**
     * Secret code used by patients to access their ticket.
     * Generated by the service when the ticket is created.
     */
    @Column(name = "access_code", nullable = false, unique = true, length = 32)
    private String accessCode;

    /** WAITING, IN_CHAIR, DONE or SKIPPED - matches TICKET_STATUS in the frontend constants. */
    @Column(name = "status", nullable = false, length = 20)
    private String status = "WAITING";

    @Column(name = "joined_at", nullable = false)
    private LocalDateTime joinedAt = LocalDateTime.now();

    public QueueTicket() {
    }

    public QueueTicket(
            Queue queue,
            Patient patient,
            MedicalService medicalService,
            Integer ticketNumber
    ) {
        this.queue = queue;
        this.patient = patient;
        this.medicalService = medicalService;
        this.ticketNumber = ticketNumber;
        this.status = "WAITING";
        this.joinedAt = LocalDateTime.now();
    }

    public Integer getTicketId() {
        return ticketId;
    }

    public void setTicketId(Integer ticketId) {
        this.ticketId = ticketId;
    }

    public Queue getQueue() {
        return queue;
    }

    public void setQueue(Queue queue) {
        this.queue = queue;
    }

    public Patient getPatient() {
        return patient;
    }

    public void setPatient(Patient patient) {
        this.patient = patient;
    }

    public MedicalService getMedicalService() {
        return medicalService;
    }

    public void setMedicalService(MedicalService medicalService) {
        this.medicalService = medicalService;
    }

    public Appointment getAppointment() {
        return appointment;
    }

    public void setAppointment(Appointment appointment) {
        this.appointment = appointment;
    }

    public Integer getTicketNumber() {
        return ticketNumber;
    }

    public void setTicketNumber(Integer ticketNumber) {
        this.ticketNumber = ticketNumber;
    }

    public String getAccessCode() {
        return accessCode;
    }

    public void setAccessCode(String accessCode) {
        this.accessCode = accessCode;
    }

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        this.status = status;
    }

    public LocalDateTime getJoinedAt() {
        return joinedAt;
    }

    public void setJoinedAt(LocalDateTime joinedAt) {
        this.joinedAt = joinedAt;
    }
}
